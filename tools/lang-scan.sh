#!/bin/sh
# lang-scan.sh — 语言纪律机械扫描（§三十二·四／二七／v6.1 P1-3）
# v6.1：双组扫描——A 组字面命中=违规；B 组语义近似命中=警告须人工复核
# 用法：sh tools/lang-scan.sh <被扫描文本文件>
FILE="${1:?用法: lang-scan.sh <文本文件>}"
echo "=== 语言纪律扫描（v6.1 A组字面/B组近似）==="
echo "--- A 组（字面·命中即违规）---"
if grep -nE "候选|倾向|指向|疑似|预登记|锚定" "$FILE"; then
  echo "⛔ A 组违规：见上，该单元作废重做（规则46/三十二·四）"
else
  echo "✅ A 组通过：无禁用词汇"
fi
echo "--- B 组（语义近似·命中须逐句人工复核）---"
if grep -nE "像是|朝向|偏向|接近这个话题|更像|某种感觉上是|给人感觉" "$FILE"; then
  echo "⚠️ B 组嫌疑：以上行须人工复核语义并贴结论（否则按规则46 语义判定违规）"
else
  echo "✅ B 组通过：无近似词"
fi
echo "=== 扫描结束 ==="
