#!/bin/sh
# line-refresh.sh — 行号速查表刷新/校验（§三十一·三）
# 用法：sh tools/line-refresh.sh [19号文件路径] [--snapshot]
#   --snapshot：仅更新本次 iter 的快照（v6.1 调用后执行，登记新快照）
# 功能：①输出当前全部主锚点行号 ②与内置 §三十一·一 快照比对 → 自动漂移报告
#       ③漂移时给出"刷新模板"（可人工替换快照后重跑）
F="${1:-references/19-typing-workflow.md}"
SNAP_VER="v6.3+禁令20261109"

# ===== 内置快照（v6.1.1·2026-11-06 最终实测；与 §三十一·一 总表一致）=====
# 格式：grep锚点正则 | 期望行号 | 说明
snapshot() { cat <<'SNAP'
^## §零·〇|91|§零·〇 执行铁律
^## §零、启动防护|306|§零 启动防护
^## §零·一、解散对照表|325|§零·一
^## 一、证据规则|374|§一 证据规则
^## Layer 1：逐题信号全提取|606|Layer 1
^## Layer 1.1：功能识别|747|Layer 1.1
^## Layer 1.2：逐题位置假设矩阵|778|Layer 1.2
^## Layer 1.3：维度路线|850|Layer 1.3
^## Layer 1.4：电荷路线|922|Layer 1.4
^## Layer 1.5：冲突/邻近关系预检|1007|Layer 1.5
^## Layer 1.6：题目间关联分析|1023|Layer 1.6
^## Layer 2：功能|1103|Layer 2
^## Layer 2.1：二分法路线|1142|Layer 2.1
^## Layer 3：全置信度聚合|1212|Layer 3
^## Layer 3.5：筛选|1294|Layer 3.5
^## Phase D：候选深度比对|1352|Phase D 前置
^## Layer 7：类型描述文本比对|1366|Layer 7
^## Layer 5：16 类型穷举排除|1398|Layer 5
^## Layer 6：信道审计|1426|Layer 6
^## 输出：报告模板|1638|输出
^## 十一、置信度标尺|1740|§十一
^## 二十三、v5.22|3421|增量·v5.22
^## 二十四、v5.23|3496|增量·v5.23
^## 二十五、v5.24 增补（2026-10-25）——防锚定|3565|增量·v5.24-a
^## 二十六、v5.25|3638|增量·v5.25
^## 二十五、v5.24 增补（2026-10-26）——P2|3738|增量·v5.24-b
^## 二十七、v5.26|3810|增量·v5.26
^## 二十八、v5.27|3890|增量·v5.27
^## 二十九、v5.28|3963|增量·v5.28
^## 三十、v5.28.1|4019|增量·v5.28.1
^## 三十一、当步重读行号速查表|4070|§三十一
^## 三十二、v6.0|4161|§三十二
^## 三十三、v6.1|4443|§三十三
^## 三十四、全文档段覆盖归属总表|4581|§三十四
^## 三十五、v6.2 增补|4684|§三十五
^## 三十六、v6.3 增补|4808|§三十六
^### R0.5 高危关系预登记|191|R0.5
^### R0.6 层必读文件|202|R0.6
^### R0.7 预注册杀手题|246|R0.7
^### R0.9 对偶端点预注册|261|R0.9
^### R0.10 材料可判型度预检|267|R0.10
^### R0.10b 信息缺口映射|291|R0.10b
SNAP
}

if [ "$2" = "--snapshot" ]; then
  # 仅打印当前实测，供人工抄录为新快照（升级编排用）
  echo "=== 当前实测行号（供快照更新，抄入 snapshot() 后重跑）==="
  grep -nE "^## (Layer|Phase|输出|§|一、|十一|十二|二十三|二十四|二十五|二十六|二十七|二十八|二十九|三十|三十一|三十二|三十三)|^### R0\.(5|6|7|9|10|10b)" "$F" \
    | sed -E 's#:#|#g' | sed 's/|\(.*\)$/|&/' | sed 's/^/  /'
  exit 0
fi

echo "=== 行号速查表现值 vs 内置快照(${SNAP_VER}) 自动比对 ==="
snapshot | {
  drift=0
  while IFS='|' read -r pat exp desc; do
    [ -z "$pat" ] && continue
    now=$(grep -nE "$pat" "$F" 2>/dev/null | head -1 | cut -d: -f1)
    if [ -z "$now" ]; then
      echo "  ✗ MISSING: $desc（锚点 $pat 未找到）"
      drift=$((drift+1))
    elif [ "$now" != "$exp" ]; then
      echo "  ✗ DRIFT: $desc  现值=$now 快照=${exp}（原$exp）"
      drift=$((drift+1))
    else
      echo "  ✓ OK: $desc @ $now"
    fi
  done
  echo "=== 漂移计数: $drift（>0 时须按 §三十一·三 刷新总表并登记版本头）==="
}
