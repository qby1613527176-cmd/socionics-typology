#!/bin/sh
# dual-sample.sh — 分歧强制双采样（规则34 子条款 / §三十二·二七）
# 触发：Layer 3.5 顶部两假设补丁差 ≤2 时强制；生成双采样记录，两结论并列进入候选。
# 用法：sh tools/dual-sample.sh <卷名> <分歧点描述> [目录]
VOL="${1:?用法: dual-sample.sh <卷名> <分歧点描述>}"
DESC="${2:-顶部候选补丁差≤2}"
DIR="${3:-/workspace/session-audit}"
mkdir -p "$DIR"
OUT="$DIR/$VOL-sampling.json"
cat > "$OUT" <<JSON
{
  "卷": "$VOL",
  "分歧点": "$DESC",
  "触发": "规则34子条款（补丁差≤2 强制双采样）",
  "采样1视角": "待填（如：原流程视角）",
  "采样2视角": "待填（如：对抗性视角/换句法重读）",
  "采样1结论": "待填",
  "采样2结论": "待填",
  "两结论关系": "待填（并列/收敛/分歧）",
  "处置": "两结论均进入候选；分歧时按规则17 双假设"
}
JSON
echo "DUAL_SAMPLE_FILE: $OUT（请填两采样视角与结论，并列呈现防同源）"
